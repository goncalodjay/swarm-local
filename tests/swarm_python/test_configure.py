"""`swarm-kura change` (swarm_python/configure.py): editing swarmforge.conf rows
without the full wizard, and the session fingerprint that makes a changed role
start a fresh agent session."""

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

SCRIPTS = Path(__file__).resolve().parents[2] / "template" / "swarmforge" / "scripts"
sys.path.insert(0, str(SCRIPTS))

from swarm_python import configure  # noqa: E402
from swarm_python.sessions import backend_fingerprint, plan_session  # noqa: E402

CONF = """# Generated by swarm-init.
window specifier opencode master --model opencode-go/kimi-k2.7-code --agent build --auto
window coder claude coder --model sonnet --effort high --dangerously-skip-permissions
window reviewer codex reviewer --model gpt-5.6-luna -c model_reasoning_effort=high --dangerously-bypass-approvals-and-sandbox
window architect hermes architect batch --provider opencode-go --model minimax-m3 --reasoning medium --yolo
window extra pi extra --model openai-codex/gpt-5.4-mini --thinking low
window fast grok fast --model grok-3 --permission-mode bypassPermissions
"""


class ParseRenderTests(unittest.TestCase):
    def test_every_row_round_trips_unchanged(self):
        lines, rows = configure.parse_conf(CONF)
        self.assertEqual(len(rows), 6)
        for row in rows:
            self.assertEqual(configure.render_row(row), " ".join(lines[row.line_index].split()))

    def test_parse_extracts_model_thinking_and_auto_approve(self):
        _, rows = configure.parse_conf(CONF)
        by = {r.role: r.backend for r in rows}
        self.assertEqual((by["specifier"].provider, by["specifier"].model), ("opencode-go", "kimi-k2.7-code"))
        self.assertEqual(by["specifier"].others, ["--agent", "build"])
        self.assertTrue(by["specifier"].auto_approve)
        self.assertEqual(by["coder"].thinking, "high")
        self.assertEqual(by["reviewer"].thinking, "high")
        self.assertEqual((by["architect"].provider, by["architect"].thinking), ("opencode-go", "medium"))
        self.assertTrue(by["fast"].auto_approve)  # two-token flag

    def test_receive_mode_and_worktree_are_kept(self):
        _, rows = configure.parse_conf(CONF)
        arch = [r for r in rows if r.role == "architect"][0]
        configure.change_agent(arch, "codex", "", "gpt-5.6-luna", "high")
        self.assertTrue(configure.render_row(arch).startswith("window architect codex architect batch --model gpt-5.6-luna"))


class ChangeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name).resolve()
        (self.root / "swarmforge").mkdir()
        self.conf = self.root / "swarmforge" / "swarmforge.conf"
        self.conf.write_text(CONF, encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def run_change(self, *argv):
        err = io.StringIO()
        with contextlib.redirect_stderr(err), mock.patch.object(sys.stdin, "isatty", return_value=False):
            code = configure.main(["--project", str(self.root), *argv])
        return code, err.getvalue(), self.conf.read_text(encoding="utf-8")

    def row(self, text, role):
        return [line for line in text.splitlines() if line.startswith(f"window {role} ")][0]

    def test_model_only_change_keeps_other_args(self):
        code, _, text = self.run_change("specifier", "--model", "opencode-go/kimi-k3", "-y")
        self.assertEqual(code, 0)
        self.assertEqual(self.row(text, "specifier"),
                         "window specifier opencode master --model opencode-go/kimi-k3 --agent build --auto")
        self.assertEqual(self.row(text, "coder"), CONF.splitlines()[2])  # untouched
        self.assertTrue(list((self.root / "swarmforge").glob("swarmforge.conf.bak.*")))

    def test_switch_every_claude_role_to_codex_keeps_auto_approve(self):
        code, _, text = self.run_change("--from-agent", "claude", "--agent", "codex", "--model", "gpt-5.6-luna", "-y")
        self.assertEqual(code, 0)
        self.assertEqual(self.row(text, "coder"),
                         "window coder codex coder --model gpt-5.6-luna -c model_reasoning_effort=high "
                         "--dangerously-bypass-approvals-and-sandbox")

    def test_agent_change_without_model_fails_without_terminal(self):
        code, err, text = self.run_change("coder", "--agent", "codex")
        self.assertEqual(code, 1)
        self.assertIn("--model", err)
        self.assertEqual(text, CONF)

    def test_thinking_only_for_all_roles(self):
        code, _, text = self.run_change("--all", "--thinking", "xhigh", "-y")
        self.assertEqual(code, 0)
        self.assertIn("--effort xhigh", self.row(text, "coder"))
        self.assertIn("--reasoning xhigh", self.row(text, "architect"))
        self.assertIn("--thinking xhigh", self.row(text, "extra"))

    def test_unknown_role_changes_nothing(self):
        code, err, text = self.run_change("nobody", "--model", "x", "-y")
        self.assertEqual(code, 1)
        self.assertIn("nobody", err)
        self.assertEqual(text, CONF)

    def test_pi_to_claude_takes_auto_approve_from_the_other_rows(self):
        code, _, text = self.run_change("extra", "--agent", "claude", "--model", "opus", "-y")
        self.assertEqual(code, 0)
        self.assertEqual(self.row(text, "extra"),
                         "window extra claude extra --model opus --effort low --dangerously-skip-permissions")


class SessionFingerprintTests(unittest.TestCase):
    def test_same_backend_resumes(self):
        fp = backend_fingerprint("claude", "--model sonnet")
        st = {"task": "feat", "session_id": "u-1", "backend": fp}
        plan = plan_session("claude", "coder", "feat", st, fp)
        self.assertTrue(plan.resume)

    def test_changed_model_starts_fresh(self):
        st = {"task": "feat", "session_id": "u-1", "backend": backend_fingerprint("claude", "--model sonnet")}
        plan = plan_session("claude", "coder", "feat", st, backend_fingerprint("claude", "--model opus"))
        self.assertFalse(plan.resume)
        self.assertNotEqual(plan.session_id, "u-1")

    def test_state_without_fingerprint_still_resumes(self):
        # State written before the fingerprint existed keeps resuming.
        st = {"task": "feat", "session_id": "u-1"}
        self.assertTrue(plan_session("pi", "coder", "feat", st, backend_fingerprint("pi", "")).resume)


if __name__ == "__main__":
    unittest.main()
